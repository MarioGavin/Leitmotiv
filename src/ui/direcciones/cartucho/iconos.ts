/** Convierte un mapa de bits en el atributo `d` de un trazado: un rectángulo por cada tira horizontal de píxeles. */
export function trazadoDe(filas: readonly string[]): string {
  let d = ''
  filas.forEach((fila, y) => {
    let x = 0
    while (x < fila.length) {
      if (fila[x] !== '#') {
        x++
        continue
      }
      let fin = x
      while (fila[fin] === '#') fin++
      d += `M${x} ${y}h${fin - x}v1h-${fin - x}z`
      x = fin
    }
  })
  return d
}

const trazados = new Map<NombreDeIcono, string>()

export function trazadoDeIcono(nombre: NombreDeIcono): string {
  let d = trazados.get(nombre)
  if (d === undefined) {
    d = trazadoDe(MAPAS_DE_BITS[nombre])
    trazados.set(nombre, d)
  }
  return d
}
